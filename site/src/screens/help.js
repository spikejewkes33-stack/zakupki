// «Как настроить «Команду»» — инструкция по сборке «Команды» iPhone. Единственный источник:
// файл komanda-instrukciya.md в папке проекта только ссылается сюда.
import { html, useState, Header, toast } from '../ui.js';

// Кнопка «Скопировать»: чтобы не набирать ===PDD===, PDD.txt и 订单 вручную.
function Copy({ text }) {
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
      toast(`Скопировано: ${text}`);
    } catch {
      toast('Не скопировалось — выделите текст пальцем');
    }
  };
  return html`<span class="copy"><code>${text}</code><button class="btn small" onClick=${copy}>Скопировать</button></span>`;
}

const KEY = 'help-done';
function loadDone() {
  try {
    return JSON.parse(localStorage.getItem(KEY) || '[]');
  } catch {
    return [];
  }
}

// Шаг с галочкой «сделано»: пока собираете «Команду», видно, где остановились.
function Step({ id, n, done, toggle, children }) {
  const on = done.includes(id);
  return html`<li class=${`help-step ${on ? 'done' : ''}`}>
    <button class="help-check" aria-label=${on ? 'Снять отметку' : 'Отметить как сделано'} onClick=${() => toggle(id)}>${on ? '✓' : n}</button>
    <div class="help-text">${children}</div>
  </li>`;
}

const S = ({ children }) => html`<span class="search-word">${children}</span>`;

export function HelpScreen() {
  const [done, setDone] = useState(loadDone);
  const toggle = (id) => {
    const next = done.includes(id) ? done.filter((x) => x !== id) : [...done, id];
    setDone(next);
    try {
      localStorage.setItem(KEY, JSON.stringify(next));
    } catch {
      /* без памяти — просто не запомнится */
    }
  };
  const p = { done, toggle };
  return html`<${Header} title="Как настроить «Команду»" back=${true} />
  <main class="help">
    <section class="card">
      <p>Одно нажатие <b>Кнопки действия</b> на экране Pinduoduo снимает экран, распознаёт текст и дописывает его в файл <b>PDD.txt</b> (iCloud Drive → Shortcuts). Телефон коротко вибрирует.</p>
      <p>Потом здесь, в «Закупках», кнопка <b>«Забрать из PDD»</b> сама раскладывает товары по клиентам и треки по товарам.</p>
      <p class="muted">Собрать один раз, около 5 минут. Готовую «Команду» прислать нельзя (Apple подписывает их только на Mac), поэтому собираем на iPhone. Галочки слева помогают не потеряться.</p>
    </section>

    <section class="card warn">
      <p><b>Снимки сами в приложение не попадают.</b> «Команда» только копит их в файле PDD.txt. Чтобы они появились в «Закупках», откройте Главную → <b>«📥 Забрать из PDD»</b> → выберите PDD.txt.</p>
    </section>
    <section class="card info">
      <p>Названия действий в вашей iOS могут чуть отличаться. Если не нашли по названию — пишите в поиск слово в <span class="search-word">рамке</span>.</p>
    </section>

    <h2>Сборка</h2>
    <section class="card">
      <p><b>Если пробная «Команда» уже есть</b> (снимок → текст → «Показать результат», висит на Кнопке действия): откройте её в «Командах», удалите последнее действие «Показать результат» (смахните влево или крестик) и начните со <b>шага 3.3</b>. Название можно оставить своё.</p>
    </section>
    <ol class="help-steps">
      <${Step} id="s1" n="1" ...${p}>Откройте приложение <b>«Команды»</b> → вкладка «Быстрые команды» → <b>«+»</b> справа вверху.</${Step}>
      <${Step} id="s2" n="2" ...${p}>Назовите команду <b>PDD</b>: нажмите на название вверху → «Переименовать».</${Step}>
      <li class="help-sub">3. Нажмите «Поиск действий» и добавьте по порядку:</li>
      <${Step} id="a1" n="3.1" ...${p}><b>«Сделать снимок экрана»</b> — поиск <${S}>снимок</${S}>.</${Step}>
      <${Step} id="a2" n="3.2" ...${p}><b>«Извлечь текст из изображения»</b> — поиск <${S}>извлечь текст</${S}>. Оно само возьмёт снимок из шага 3.1.</${Step}>
      <${Step} id="a3" n="3.3" ...${p}><b>«Текущая дата»</b> — поиск <${S}>текущая дата</${S}>.</${Step}>
      <${Step} id="a4" n="3.4" ...${p}><b>«Форматировать дату»</b> — поиск <${S}>форматировать дату</${S}>. Нажмите «Формат даты» → выберите <b>ISO 8601</b>, включите <b>время</b> («Включить время ISO 8601»).</${Step}>
      <${Step} id="a5" n="3.5" ...${p}>
        <b>«Текст»</b> — поиск <${S}>текст</${S}>, действие с жёлтым значком. Впишите ровно три строки:
        <ol class="help-lines">
          <li>первая: <${Copy} text="===PDD===" /></li>
          <li>вторая: нажмите над клавиатурой переменную <b>«Отформатированная дата»</b></li>
          <li>третья: переменная <b>«Текст из изображения»</b> (если её нет над клавиатурой — «Выбрать переменную» → действие «Извлечь текст из изображения»)</li>
        </ol>
      </${Step}>
      <${Step} id="a6" n="3.6" ...${p}>
        <b>«Добавить в текстовый файл»</b> — поиск <${S}>текстовый файл</${S}>. Поставьте:
        <ul class="help-lines">
          <li>что добавлять — <b>«Текст»</b> из шага 3.5 (обычно подставится само);</li>
          <li>путь к файлу — <${Copy} text="PDD.txt" /></li>
          <li><b>«Новая строка»</b> — обязательно включено.</li>
        </ul>
      </${Step}>
      <${Step} id="a7" n="3.7" ...${p}><b>«Вибрировать»</b> (может называться «Вибрация») — поиск <${S}>вибр</${S}>. Так вы почувствуете, что снимок записан.</${Step}>
      <${Step} id="a8" n="3.8" ...${p}>
        <span class="muted">Необязательно, но полезно:</span> <b>«Если»</b> — поиск <${S}>если</${S}>. Условие: «Текст из изображения» → <b>не содержит</b> → <${Copy} text="订单" />
        Внутрь «Если» добавьте <b>«Показать уведомление»</b> (поиск <${S}>уведомление</${S}>) с текстом «Не прочитал — снимите ещё раз». Так сразу видно, если снимок попал на анимацию перехода.
      </${Step}>
      <${Step} id="s4" n="4" ...${p}>Нажмите <b>«Готово»</b>.</${Step}>
      <${Step} id="s5" n="5" ...${p}>Кнопка действия: <b>Настройки → Кнопка действия</b> → листайте до <b>«Быстрая команда»</b> → выберите <b>PDD</b>.</${Step}>
    </ol>

    <h2>Проверка (1 минута)</h2>
    <ol class="help-steps">
      <${Step} id="c1" n="1" ...${p}>Откройте любой заказ в Pinduoduo (экран с «实付» и «订单号») и нажмите Кнопку действия. Должна быть вибрация.</${Step}>
      <${Step} id="c2" n="2" ...${p}>При первом запуске iOS один раз спросит разрешение (снимок экрана, запись в файл) прямо поверх PDD — нажмите <b>«Разрешить всегда»</b>.</${Step}>
      <${Step} id="c3" n="3" ...${p}><b>Проверьте, что файл появился:</b> приложение «Файлы» → «Обзор» → iCloud Drive → папка <b>Shortcuts</b> (может называться «Быстрые команды») → <b>PDD.txt</b>. Нажмите на него: внутри «===PDD===», дата и китайский текст экрана.
        <div class="muted small">Файла нет — значит, «Команда» ещё пробная («Показать результат») или в шаге 3.6 другой путь. Окно с текстом после нажатия — тоже признак пробной «Команды».</div></${Step}>
      <${Step} id="c4" n="4" ...${p}>В «Закупках»: Главная → <b>«📥 Забрать из PDD»</b> → «Выбрать файл PDD.txt». Приложение покажет снимок — значит, всё работает.</${Step}>
    </ol>

    <h2>Как работать</h2>
    <section class="card">
      <div class="eyebrow">Когда оформляете заказы</div>
      <ol class="help-plain">
        <li>В «Закупках»: <b>«Начать оформление клиента»</b> → выберите клиента.</li>
        <li>Оплатили товар в Pinduoduo → откройте этот заказ (订单详情) → прокрутите так, чтобы были видны <b>«实付»</b> и <b>«订单号»</b> → <b>Кнопка действия</b>. Так для каждого товара. Без номера заказа трек потом не приклеится.</li>
        <li>В «Закупках»: <b>«Завершить заказы клиента»</b> → следующий клиент.</li>
      </ol>
      <p class="muted small">Клиент определяется по времени нажатия: всё, что снято между «Начать» и «Завершить» клиента, — его.</p>
    </section>
    <section class="card">
      <div class="eyebrow">Когда продавец отправил</div>
      <p>В заказе «查看物流» (логистика) → дождитесь, пока экран откроется полностью (видны трек и «订单编号») → <b>Кнопка действия</b> → назад. Трек сам приклеится к товару по номеру заказа.</p>
      <p class="muted small">Если сначала сняли логистику, а экран заказа позже — трек подождёт и приклеится сам.</p>
    </section>
    <section class="card">
      <div class="eyebrow">Забрать в приложение (хоть раз в день)</div>
      <ol class="help-plain">
        <li>Главная → <b>«Забрать из PDD»</b> → «Выбрать файл PDD.txt» → «Обзор» → iCloud Drive → Shortcuts → PDD.txt.</li>
        <li>Приложение покажет, сколько товаров добавит и к кому, сколько треков привяжет и какие снимки не поняло. Можно поправить клиента, количество, сумму, вписать русское название.</li>
        <li><b>«Записать»</b>.</li>
      </ol>
      <p class="muted small">Тот же файл можно забирать сколько угодно раз — уже забранное не задвоится. Большой файл можно удалить в «Файлах»: «Команда» создаст новый.</p>
      <a class="btn primary block" href="#/import">Открыть «Забрать из PDD»</a>
    </section>

    <h2>Что приложение берёт со снимков</h2>
    <section class="card">
      <p><b>Экран заказа:</b> название, вариант, <b>实付</b> (сколько реально заплачено), количество «×N», номер заказа. <span class="muted">Не берёт цену до скидки и цены из ленты «рекомендуем».</span></p>
      <p><b>Логистика:</b> перевозчик и трек, номер заказа, статус (в пути / 已签收 = на складе). <span class="muted">Не берёт телефон курьера и надписи с карты.</span></p>
      <p>Китайское название сохраняется как есть. Для описи нужно русское: впишите его при «Забрать» или в описи (строка с пометкой «нет рус.»). Перевод запомнится для таких же товаров.</p>
    </section>

    <h2>Пока не умеет</h2>
    <section class="card">
      <p><b>Фото товара</b> со снимка: картинка на экране заказа стоит в разных местах, надёжно вырезать её «Командой» нельзя. Фото можно добавить в карточку вручную.</p>
      <p><b>Запись экрана (видео)</b> вместо нажатий — следующий шаг.</p>
    </section>
    ${done.length > 0 && html`<button class="btn block" onClick=${() => { setDone([]); try { localStorage.removeItem(KEY); } catch { /* ничего */ } }}>Снять все галочки</button>`}
  </main>`;
}
