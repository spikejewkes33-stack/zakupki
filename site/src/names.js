// Иероглифы и китайская пунктуация (в описи и в файлах их быть не должно).
export const CJK = /[\u2e80-\u2fff\u3000-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\ufe30-\ufe4f\uff00-\uffef]/;
export const hasCjk = (s) => CJK.test(String(s || ''));

// Русское название товара: своё, если оно русское; иначе по словарю из китайского; иначе пусто.
export function russianName(it) {
  const own = String(it?.name || '').trim();
  if (own && !hasCjk(own)) return own;
  return ruName(own || it?.nameCn, it?.variant) || ruName(it?.nameCn, it?.variant) || '';
}

// Самое длинное совпавшее слово — самое точное («秋衣秋裤» точнее «内衣»); при равной длине — что раньше в названии.
export function ruName(nameCn, variant = '') {
  for (const text of [nameCn, variant]) {
    const t = String(text || '');
    if (!t) continue;
    let best = null;
    for (const [cn, ru, g] of NOUNS) {
      const at = t.indexOf(cn);
      if (at < 0) continue;
      if (!best || cn.length > best.cn.length || (cn.length === best.cn.length && at < best.at)) best = { cn, ru, g, at };
    }
    if (!best) continue;
    if (best.g === 'fixed') return best.ru;
    const who = WHO.find(([re]) => re.test(t));
    return who ? `${best.ru} ${who[1][best.g]}` : best.ru;
  }
  return '';
}

