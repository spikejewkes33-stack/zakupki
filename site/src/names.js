// Короткое название из перевода, когда словарь не знает товар. ru — строки перевода всего экрана,
// bodyLen — сколько строк было в китайском тексте, titleIdx — где в нём название (номера строк).
// Перевод обычно сохраняет строки; если число строк не совпало — берём строки примерно на тех же местах.
export function nameFromTranslation(ru, bodyLen, titleIdx) {
  if (!ru?.length || !titleIdx?.length) return '';
  const pick = new Set();
  for (const i of titleIdx) {
    if (ru.length === bodyLen) pick.add(i);
    else {
      const j = Math.round((i * ru.length) / Math.max(1, bodyLen));
      for (const k of [j - 1, j, j + 1]) if (k >= 0 && k < ru.length) pick.add(k);
    }
  }
  const text = [...pick].sort((a, b) => a - b).map((k) => ru[k]).join(' ');
  const words = text.toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я-]+/).filter(Boolean);
  const hit = words.find((w) => RU_NOUNS.has(w) || RU_NOUNS.has(w.replace(/е/g, 'ё')));
  if (hit) return cap(hit);
  // Нет знакомого слова — первые слова перевода без цифр, брендов латиницей и рекламы.
  const junk = /^(новый|новая|новое|новые|официальный|флагманский|магазин|распродажа|скидка|бесплатная|доставка|горячая|продажа|оригинал|оригинальный|сезон|модный|модная|стиль|для|и|с|в|на|из)$/;
  const plain = text.replace(/[^а-яё\s-]/gi, ' ').split(/\s+/).filter((w) => w.length > 2 && !junk.test(w.toLowerCase()));
  return plain.length ? cap(plain.slice(0, 3).join(' ').toLowerCase()) : '';
}
